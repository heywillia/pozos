-- Esquema de Mapa de Pozos (ya ejecutado en Supabase, guardado como referencia)

create table public.pozos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  lat double precision not null,
  lng double precision not null,
  tamano text not null check (tamano in ('Chico','Mediano','Crater')),
  municipio text not null,
  estado text not null default 'reportado'
    check (estado in ('reportado','verificado','arreglado')),
  confirmaciones int not null default 1,
  arreglado_at timestamptz,
  device_id uuid not null
);

create table public.votos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  pozo_id bigint not null references public.pozos(id) on delete cascade,
  device_id uuid not null,
  tipo text not null check (tipo in ('sigue','arreglado')),
  unique (pozo_id, device_id)
);

create index idx_pozos_estado on public.pozos(estado);
create index idx_pozos_municipio on public.pozos(municipio);

alter table public.pozos enable row level security;
alter table public.votos enable row level security;

create policy "lectura publica pozos" on public.pozos for select using (true);
create policy "crear pozos" on public.pozos for insert with check (true);
create policy "actualizar pozos" on public.pozos for update using (true);
create policy "lectura publica votos" on public.votos for select using (true);
create policy "crear votos" on public.votos for insert with check (true);
